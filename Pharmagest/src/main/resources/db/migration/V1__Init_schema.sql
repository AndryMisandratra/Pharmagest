    vente_id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    patient_id                       BIGINT,
    ordonnance_id                    BIGINT,
    vendeur_id                       BIGINT                                  NOT NULL,
    vente_reference                  VARCHAR(30)                             NOT NULL,
    vente_montant_total_ht           DECIMAL(12, 2)                          NOT NULL,
    vente_montant_tva                DECIMAL(12, 2)                          NOT NULL,
    vente_montant_total_ttc          DECIMAL(12, 2)                          NOT NULL,
