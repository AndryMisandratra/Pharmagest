CREATE TABLE categories_medicament
(
    categorie_id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    categorie_code        VARCHAR(20)                             NOT NULL,
    categorie_libelle     VARCHAR(100)                            NOT NULL,
    categorie_description TEXT,
    CONSTRAINT pk_categories_medicament PRIMARY KEY (categorie_id)
);

CREATE TABLE commandes_fournisseur
(
    commande_id                     BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fournisseur_id                  BIGINT                                  NOT NULL,
    createur_id                     BIGINT                                  NOT NULL,
    valideur_id                     BIGINT,
    commande_reference              VARCHAR(30)                             NOT NULL,
    commande_statut                 VARCHAR(30)                             NOT NULL,
    commande_montant_total_ht       DECIMAL(14, 2),
    commande_date_commande          TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    commande_date_envoi             TIMESTAMP WITHOUT TIME ZONE,
    commande_date_reception         TIMESTAMP WITHOUT TIME ZONE,
    commande_date_livraison_estimee date,
    commande_notes                  TEXT,
    CONSTRAINT pk_commandes_fournisseur PRIMARY KEY (commande_id)
);

CREATE TABLE fournisseurs
(
    fournisseur_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    fournisseur_raison_sociale        VARCHAR(200)                            NOT NULL,
    fournisseur_email                 VARCHAR(150),
    fournisseur_telephone             VARCHAR(25),
    fournisseur_adresse               TEXT,
    fournisseur_delai_livraison_jours INTEGER,
    fournisseur_est_actif             BOOLEAN                                 NOT NULL,
    fournisseur_cree_le               TIMESTAMP WITHOUT TIME ZONE             NOT NULL,
    CONSTRAINT pk_fournisseurs PRIMARY KEY (fournisseur_id)
);

CREATE TABLE lignes_commande
(
    ligne_commande_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    commande_id                          BIGINT                                  NOT NULL,
    medicament_id                        BIGINT                                  NOT NULL,
    ligne_commande_quantite_commandee    INTEGER                                 NOT NULL,
    ligne_commande_quantite_recue        INTEGER                                 NOT NULL,
    ligne_commande_prix_achat_ht         DECIMAL(10, 2),
    ligne_commande_lot_numero_recu       VARCHAR(50),
    ligne_commande_date_peremption_recue date,
    ligne_commande_date_fabrication_recue date,
    CONSTRAINT pk_lignes_commande PRIMARY KEY (ligne_commande_id)
);

CREATE TABLE lignes_vente
(
    ligne_vente_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    vente_id                       BIGINT                                  NOT NULL,
    medicament_id                  BIGINT                                  NOT NULL,
    lot_id                         BIGINT                                  NOT NULL,
    ligne_vente_quantite           INTEGER                                 NOT NULL,
    ligne_vente_prix_unitaire_ttc  DECIMAL(10, 2)                          NOT NULL,
    ligne_vente_prix_unitaire_ht   DECIMAL(10, 2)                          NOT NULL,
    ligne_vente_taux_tva           DECIMAL(5, 2)                           NOT NULL,
